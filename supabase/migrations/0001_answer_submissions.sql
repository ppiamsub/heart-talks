create table if not exists public.answer_submissions (
  id bigint generated by default as identity primary key,
  responder_name text not null default 'ยู',
  answers_json jsonb not null,
  consent_version text not null default 'v1',
  created_at timestamptz not null default now()
);

alter table public.answer_submissions enable row level security;

revoke all on table public.answer_submissions from anon, authenticated;
grant select, insert on table public.answer_submissions to service_role;
grant usage, select on sequence public.answer_submissions_id_seq to service_role;
